# Builds review_and_overhaul/INDEX.md from the frontmatter of all item files,
# and validates that frontmatter. Base R only.

`%||%` <- function(x, y) if (is.null(x)) y else x
#
# Usage (from anywhere):  Rscript review_and_overhaul/tools/build_index.R

get_root <- function() {
  file_arg <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
  if (length(file_arg) == 1) {
    return(normalizePath(file.path(dirname(sub("^--file=", "", file_arg)), "..")))
  }
  if (dir.exists("review_and_overhaul")) return(normalizePath("review_and_overhaul"))
  normalizePath(".")
}
root <- get_root()

parse_frontmatter <- function(path) {
  lines <- readLines(path, warn = FALSE, encoding = "UTF-8")
  if (length(lines) == 0 || lines[1] != "---") stop("No frontmatter in ", path, call. = FALSE)
  end <- which(lines == "---")[2]
  if (is.na(end)) stop("Unterminated frontmatter in ", path, call. = FALSE)
  out <- list()
  for (ln in lines[2:(end - 1)]) {
    if (!nzchar(trimws(ln))) next
    key <- trimws(sub(":.*$", "", ln))
    val <- trimws(sub("^[^:]*:", "", ln))
    if (grepl("^\\[.*\\]$", val)) {
      inner <- trimws(substr(val, 2, nchar(val) - 1))
      val <- if (nzchar(inner)) trimws(strsplit(inner, ",")[[1]]) else character(0)
    }
    out[[key]] <- val
  }
  out$file <- basename(path)
  out$dir <- basename(dirname(path))
  out
}

allowed <- list(
  severity = c("critical", "high", "medium", "low"),
  type = c("bug", "design", "performance", "security", "maintainability", "test", "docs", "dependency", "i18n"),
  status = c("open", "in-progress", "needs-decision", "fixed", "verified", "wontfix", "duplicate"),
  verification = c("verified", "reading"),
  effort = c("S", "M", "L", "XL"),
  api_change = c("no", "possible", "yes")
)
required <- list(
  findings = c("id", "title", "severity", "type", "area", "status", "verification", "effort", "api_change", "locations", "related", "origin", "commit", "created", "updated"),
  ideas = c("id", "title", "area", "status", "effort", "api_change", "related", "origin", "created", "updated"),
  decisions = c("id", "title", "area", "status", "related", "origin", "created", "updated"),
  reviews = c("id", "title", "status", "commit", "created", "updated")
)
prefix <- c(findings = "F", ideas = "I", decisions = "D", reviews = "R")

items <- list()
problems <- character(0)
for (d in names(prefix)) {
  files <- list.files(file.path(root, d), pattern = "\\.md$", full.names = TRUE)
  files <- files[!grepl("^README", basename(files))]
  for (f in files) {
    fm <- tryCatch(parse_frontmatter(f), error = function(e) {
      problems <<- c(problems, conditionMessage(e)); NULL
    })
    if (is.null(fm)) next
    miss <- setdiff(required[[d]], names(fm))
    if (length(miss)) problems <- c(problems, paste0(fm$file, ": missing field(s) ", toString(miss)))
    if (!is.null(fm$id) && !startsWith(basename(f), paste0(fm$id, "_")))
      problems <- c(problems, paste0(fm$file, ": file name must start with '", fm$id, "_'"))
    if (!is.null(fm$id) && !grepl(paste0("^", prefix[[d]], "[0-9]+$"), fm$id))
      problems <- c(problems, paste0(fm$file, ": id '", fm$id, "' does not match prefix ", prefix[[d]]))
    for (k in intersect(names(allowed), names(fm))) {
      if (!all(fm[[k]] %in% allowed[[k]]))
        problems <- c(problems, paste0(fm$file, ": invalid ", k, " '", toString(fm[[k]]), "'"))
    }
    items[[length(items) + 1]] <- fm
  }
}

ids <- vapply(items, function(x) x$id %||% NA_character_, character(1))
dups <- unique(ids[duplicated(ids)])
if (length(dups)) problems <- c(problems, paste0("duplicate id(s): ", toString(dups)))
for (it in items) {
  bad <- setdiff(it$related, ids)
  if (length(bad)) problems <- c(problems, paste0(it$file, ": related id(s) not found: ", toString(bad)))
}
if (length(problems)) {
  stop("Frontmatter problems:\n- ", paste(problems, collapse = "\n- "), call. = FALSE)
}

of_kind <- function(d) Filter(function(x) x$dir == d, items)
esc <- function(x) gsub("|", "\\|", x, fixed = TRUE)
link <- function(x) sprintf("[%s](%s/%s)", x$id, x$dir, x$file)
next_id <- function(d) {
  n <- suppressWarnings(as.integer(sub("^[A-Z]", "", vapply(of_kind(d), `[[`, "", "id"))))
  width <- if (d == "reviews") 2 else 3
  sprintf(paste0("%s%0", width, "d"), prefix[[d]], max(c(0L, n), na.rm = TRUE) + 1L)
}
sev_rank <- function(s) match(s, allowed$severity)
open_status <- c("open", "in-progress", "needs-decision")

findings <- of_kind("findings")
findings <- findings[order(vapply(findings, function(x) sev_rank(x$severity), 1), vapply(findings, `[[`, "", "id"))]

out <- c(
  "# Index",
  "",
  paste0("Generated by `tools/build_index.R` on ", format(Sys.time(), "%Y-%m-%d %H:%M"), ". Do not edit by hand."),
  "",
  paste0("Next free IDs: ", paste(vapply(names(prefix), next_id, ""), collapse = ", "), "."),
  "",
  "## Findings at a glance",
  "",
  paste0("| severity | ", paste(allowed$status, collapse = " | "), " | total |"),
  paste0("|---", strrep("|---", length(allowed$status)), "|---|")
)
for (s in allowed$severity) {
  st <- vapply(Filter(function(x) x$severity == s, findings), `[[`, "", "status")
  out <- c(out, paste0("| ", s, " | ", paste(vapply(allowed$status, function(a) sum(st == a), 1), collapse = " | "), " | ", length(st), " |"))
}

finding_table <- function(lst) {
  if (!length(lst)) return("_None._")
  c("| ID | severity | title | area | type | status | verif. | effort | API |",
    "|---|---|---|---|---|---|---|---|---|",
    vapply(lst, function(x) sprintf("| %s | %s | %s | %s | %s | %s | %s | %s | %s |",
                                    link(x), x$severity, esc(x$title), x$area, x$type, x$status,
                                    x$verification, x$effort, x$api_change), ""))
}
is_open <- function(x) x$status %in% open_status
out <- c(out, "", "## Open findings", "", finding_table(Filter(is_open, findings)))
nd <- Filter(function(x) x$status == "needs-decision", findings)
out <- c(out, "", "## Awaiting a maintainer decision", "",
         if (length(nd)) vapply(nd, function(x) paste0("- ", link(x), ": ", esc(x$title)), "") else "_None._")
out <- c(out, "", "## Closed findings", "", finding_table(Filter(Negate(is_open), findings)))

simple_table <- function(lst, cols) {
  if (!length(lst)) return("_None yet._")
  c(paste0("| ID | ", paste(cols, collapse = " | "), " |"),
    paste0("|---", strrep("|---", length(cols)), "|"),
    vapply(lst, function(x) paste0("| ", link(x), " | ",
                                   paste(vapply(cols, function(k) esc(paste(x[[k]] %||% "", collapse = ", ")), ""), collapse = " | "),
                                   " |"), ""))
}
out <- c(out,
         "", "## Ideas", "", simple_table(of_kind("ideas"), c("title", "area", "status", "effort", "api_change")),
         "", "## Decisions", "", simple_table(of_kind("decisions"), c("title", "area", "status")),
         "", "## Review rounds", "", simple_table(of_kind("reviews"), c("title", "commit", "created")),
         "")

writeLines(out, file.path(root, "INDEX.md"), useBytes = TRUE)
cat("INDEX.md written:", length(findings), "findings,", length(of_kind("ideas")), "ideas,",
    length(of_kind("decisions")), "decisions,", length(of_kind("reviews")), "reviews.\n")
cat("Next free IDs:", vapply(names(prefix), next_id, ""), "\n")
